/**
 * Rewrites `dist/src/gltf-web.js` so a browser bundler never resolves `NodeIO`.
 *
 * `tsc` emits a re-export of `@gltf-transform/core`. `NodeIO` lives in that same module
 * and dynamically imports `node:fs` and `node:path`. esbuild on `platform: "browser"`
 * resolves that import while parsing the file and fails the build, even though tree-shaking
 * would drop the class (#420). This step inlines the symbols the package actually exports
 * and leaves `NodeIO` out.
 *
 * esbuild is the devDependency Orb Run already uses for its bundle tests. Run this from
 * the package directory, after `tsc`:
 *   node ../../scripts/bundle-gltf-web.mjs
 */
import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const require = createRequire(new URL("../examples/orb-run/package.json", import.meta.url));
const { build } = require("esbuild");

const pkgRoot = process.cwd();
const entry = resolve(pkgRoot, "dist", "src", "gltf-web.js");

const before = await readFile(entry, "utf8");
if (!before.includes("@gltf-transform/core")) {
  throw new Error(`${entry} is not the tsc re-export of @gltf-transform/core. Run tsc before this step.`);
}

const exported = [...before.matchAll(/export\s*\{([^}]+)\}/g)]
  .flatMap((match) => match[1].split(","))
  .map((part) => part.trim().split(/\s+as\s+/).pop())
  .filter((name) => name && name !== "from");
if (exported.length === 0) {
  throw new Error(`${entry} does not export any glTF symbols`);
}

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  logLevel: "silent",
  plugins: [
    {
      name: "drop-node-io",
      setup(pluginBuild) {
        pluginBuild.onResolve({ filter: /^(?:node:fs|node:path|fs|path)$/ }, () => ({
          path: "empty",
          namespace: "empty-node",
        }));
        pluginBuild.onLoad({ filter: /.*/, namespace: "empty-node" }, () => ({
          contents: "export default {};",
          loader: "js",
        }));
      },
    },
  ],
});

const text = result.outputFiles?.[0]?.text;
if (!text) throw new Error("esbuild produced no gltf-web bundle");

const forbidden = ["node:fs", "node:path", 'from "fs"', 'from "path"', "require("];
const hit = forbidden.find((token) => text.includes(token));
if (hit) throw new Error(`gltf-web bundle still contains ${JSON.stringify(hit)}`);

const banner = "/* Inlined @gltf-transform/core (MIT) without NodeIO. Generated by scripts/bundle-gltf-web.mjs. */\n";
await writeFile(entry, banner + text, "utf8");

const loaded = await import(`${pathToFileURL(entry).href}?check=${Date.now()}`);
for (const name of exported) {
  if (loaded[name] === undefined) throw new Error(`gltf-web bundle is missing export ${name}`);
}
if (typeof loaded.WebIO === "function" && typeof loaded.Document === "function") {
  const doc = new loaded.Document();
  const scene = doc.createScene("s");
  doc.getRoot().setDefaultScene(scene);
  const bytes = await new loaded.WebIO().writeBinary(doc);
  if (!(bytes instanceof Uint8Array) || bytes.byteLength < 12) {
    throw new Error("gltf-web WebIO.writeBinary did not return GLB bytes");
  }
}

console.log(`gltf-web: ${exported.join(", ")} (${text.length} bytes) -> ${entry}`);
